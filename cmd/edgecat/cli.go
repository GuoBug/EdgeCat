func checkWritableSQLiteTarget(sqlitePath string) error {
	dir := filepath.Dir(sqlitePath)
	if dir == "" {
		dir = "."
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("create directory %q: %w", dir, err)
	}
	f, err := os.CreateTemp(dir, ".edgecat-check-*")
	if err != nil {
		return fmt.Errorf("directory %q is not writable: %w", dir, err)
	}
	name := f.Name()
	_ = f.Close()
	_ = os.Remove(name)
	return nil
}

func probeModelsEndpoint(ctx context.Context, client *http.Client, baseEndpoint, apiKey string) (int, error) {
	url := strings.TrimRight(strings.TrimSpace(baseEndpoint), "/") + "/models"
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return 0, err
	}
	if strings.TrimSpace(apiKey) != "" {
		req.Header.Set("Authorization", "Bearer "+strings.TrimSpace(apiKey))
	}
	resp, err := client.Do(req)
	if err != nil {
		return 0, err
	}
	defer resp.Body.Close()
	_, _ = io.Copy(io.Discard, io.LimitReader(resp.Body, 4096))
	return resp.StatusCode, nil
}

func isPlaceholderCloudKey(key string) bool {
	k := strings.TrimSpace(key)
	return k == "" || k == "sk-your-cloud-api-key" || strings.HasPrefix(k, "${")
}

func runCheck(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("check", flag.ContinueOnError)
	fs.SetOutput(stderr)
	configPath := fs.String("config", "configs/edgecat.example.yaml", "Path to YAML/JSON configuration file")
	offline := fs.Bool("offline", false, "Validate config and storage permissions only (skip live HTTP probes)")
	timeoutMs := fs.Int("timeout", 3000, "Timeout in milliseconds for upstream HTTP probes")

	if err := fs.Parse(args); err != nil {
		return 2
	}

	fmt.Fprintf(stdout, "== EdgeCat Pre-Flight Check (%s) ==\n", *configPath)

	// 1. Config & Security Invariants
	cfg, err := config.LoadConfig(*configPath)
	if err != nil {
		fmt.Fprintf(stderr, "[FAIL] Config validation: %v\n", err)
		return 1
	}
	authDesc := "disabled (loopback-only)"
	if cfg.Auth.Enabled {
		authDesc = fmt.Sprintf("enabled (%d clients)", len(cfg.Auth.Clients))
	} else if cfg.Server.AllowInsecureLAN && !config.IsLoopbackHost(cfg.Server.Host) {
		authDesc = "WARNING: allow_insecure_lan=true on non-loopback host"
	}
	fmt.Fprintf(stdout, "[OK]   Config valid: listen=%s:%d, auth=%s, pii_policy=%s, memory=%v\n",
		cfg.Server.Host, cfg.Server.Port, authDesc, cfg.Filter.Policy, cfg.Memory.Enabled)

	// 2. Storage Directories
	if err := checkWritableSQLiteTarget(cfg.Audit.SQLitePath); err != nil {
		fmt.Fprintf(stderr, "[FAIL] Audit SQLite storage (%s): %v\n", cfg.Audit.SQLitePath, err)
		return 1
	}
	fmt.Fprintf(stdout, "[OK]   Audit storage writable: %s\n", cfg.Audit.SQLitePath)

	if cfg.Memory.Enabled {
		if err := checkWritableSQLiteTarget(cfg.Memory.SQLitePath); err != nil {
			fmt.Fprintf(stderr, "[FAIL] Memory SQLite storage (%s): %v\n", cfg.Memory.SQLitePath, err)
			return 1
		}
		fmt.Fprintf(stdout, "[OK]   Memory storage writable: %s\n", cfg.Memory.SQLitePath)
	}

	if *offline {
		fmt.Fprintln(stdout, "[SKIP] Upstream connectivity probes skipped (-offline)")
		fmt.Fprintln(stdout, "Result: READY (offline check passed)")
		return 0
	}

	// 3. Live Upstream Reachability Probes
	timeout := time.Duration(*timeoutMs) * time.Millisecond
	if timeout <= 0 {
		timeout = 3 * time.Second
	}
	httpClient := &http.Client{Timeout: timeout}

	localOK := false
	if strings.TrimSpace(cfg.Local.Endpoint) != "" {
		ctx, cancel := context.WithTimeout(context.Background(), timeout)
		code, probeErr := probeModelsEndpoint(ctx, httpClient, cfg.Local.Endpoint, cfg.Local.APIKey)
		cancel()
		if probeErr == nil && code >= 200 && code < 300 {
			localOK = true
			fmt.Fprintf(stdout, "[OK]   Local Tier reachable: %s (HTTP %d)\n", cfg.Local.Endpoint, code)
		} else if probeErr != nil {
			fmt.Fprintf(stdout, "[WARN] Local Tier unreachable (%s): %v\n", cfg.Local.Endpoint, probeErr)
		} else {
			fmt.Fprintf(stdout, "[WARN] Local Tier returned HTTP %d (%s)\n", code, cfg.Local.Endpoint)
		}
	} else {
		fmt.Fprintln(stdout, "[WARN] Local Tier endpoint is empty")
	}

	cloudOK := false
	if strings.TrimSpace(cfg.Cloud.Endpoint) == "" || isPlaceholderCloudKey(cfg.Cloud.APIKey) {
		fmt.Fprintln(stdout, "[WARN] Cloud Tier API key is empty/placeholder (cloud fallback inactive until configured)")
	} else {
		ctx, cancel := context.WithTimeout(context.Background(), timeout)
		code, probeErr := probeModelsEndpoint(ctx, httpClient, cfg.Cloud.Endpoint, cfg.Cloud.APIKey)
		cancel()
		if probeErr == nil && code >= 200 && code < 300 {
			cloudOK = true
			fmt.Fprintf(stdout, "[OK]   Cloud Tier reachable: %s (HTTP %d)\n", cfg.Cloud.Endpoint, code)
		} else if probeErr != nil {
			fmt.Fprintf(stdout, "[WARN] Cloud Tier unreachable (%s): %v\n", cfg.Cloud.Endpoint, probeErr)
		} else {
			fmt.Fprintf(stdout, "[WARN] Cloud Tier returned HTTP %d (%s)\n", code, cfg.Cloud.Endpoint)
		}
	}

	if !localOK && !cloudOK {
		fmt.Fprintln(stderr, "[FAIL] Neither Local Tier nor Cloud Tier is currently reachable.")
		fmt.Fprintln(stderr, "       Hint: start Ollama ('ollama serve'), set EDGECAT_CLOUD_API_KEY / cloud.api_key, or run 'edgecat check -offline'.")
		return 1
	}

	fmt.Fprintln(stdout, "Result: READY")
	return 0
}

func resolveHealthURL(configPath, explicitURL string) (string, error) {
	if strings.TrimSpace(explicitURL) != "" {
		return strings.TrimSpace(explicitURL), nil
	}
	if strings.TrimSpace(configPath) == "" {
		return "http://127.0.0.1:8080/health", nil
	}
	cfg, err := config.LoadConfig(configPath)
	if err != nil {
		return "", err
	}
	host := strings.TrimSpace(cfg.Server.Host)
	switch host {
	case "", "0.0.0.0", "::", "[::]":
		host = "127.0.0.1"
	}
	return fmt.Sprintf("http://%s/health", net.JoinHostPort(host, strconv.Itoa(cfg.Server.Port))), nil
}

func runPing(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("ping", flag.ContinueOnError)
	fs.SetOutput(stderr)
	configPath := fs.String("config", "", "Optional config file to derive host:port")
	healthURL := fs.String("url", "", "Explicit health endpoint URL (overrides -config)")
	timeoutMs := fs.Int("timeout", 2000, "HTTP timeout in milliseconds")

	if err := fs.Parse(args); err != nil {
		return 2
	}

	targetURL, err := resolveHealthURL(*configPath, *healthURL)
	if err != nil {
		fmt.Fprintf(stderr, "[Ping] Failed to load config: %v\n", err)
		return 1
	}

	timeout := time.Duration(*timeoutMs) * time.Millisecond
	if timeout <= 0 {
		timeout = 2 * time.Second
	}
	client := &http.Client{Timeout: timeout}
	resp, err := client.Get(targetURL)
	if err != nil {
		fmt.Fprintf(stderr, "[Ping] Unhealthy (%s): %v\n", targetURL, err)
		return 1
	}
	defer resp.Body.Close()

	var body struct {
		Status string `json:"status"`
	}
	_ = json.NewDecoder(io.LimitReader(resp.Body, 4096)).Decode(&body)
	if resp.StatusCode != http.StatusOK || body.Status != "healthy" {
		fmt.Fprintf(stderr, "[Ping] Unexpected response from %s: HTTP %d (status=%q)\n", targetURL, resp.StatusCode, body.Status)
		return 1
	}

	fmt.Fprintf(stdout, "healthy (%s)\n", targetURL)
	return 0
}
